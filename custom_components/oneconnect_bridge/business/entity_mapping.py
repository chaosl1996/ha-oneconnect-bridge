"""Entity-level child mapping builder (HomeKit-Bridge style selection).

将用户在配置界面勾选的 HA 实体转换为 mapping.yaml 的 children 条目：

- switch / input_boolean → 单键开关 ZG2R（真实状态绑定）
- light → 按能力选择 ZG0S（单色）/ ZG14（亮度）/ ZG13（色温）/ ZG0O（全彩）
- lock → ZG2R 开关包装（锁定=开，解锁=关）
- script / scene / button → ZG2R 开关包装（常量 0 显示 + 命令触发）

生成的条目带 ``managed_by: entity_bridge`` 标记：合并时只增删这些条目，
用户手写的 children 永远不会被覆盖或删除。

本模块不依赖 Home Assistant，可独立单测。
"""

from __future__ import annotations

from typing import Any, Mapping

from ..const import BRIDGEABLE_DOMAINS, MAX_CHILD_DEVICES_PER_GATEWAY

MANAGED_BY_FIELD = "managed_by"
MANAGED_BY = "entity_bridge"

_SWITCH_SERVICES = [{"st": "switch", "sid": "switch1"}]


def child_key_for_entity(entity_id: str) -> str:
    """Return a stable, storage-safe child key for one HA entity id."""

    return "".join(
        char if (char.isascii() and char.isalnum()) or char in "_-" else "_"
        for char in entity_id
    )


def is_managed_child(child: Any) -> bool:
    """Return whether a raw mapping child was generated by the entity bridge."""

    return isinstance(child, dict) and child.get(MANAGED_BY_FIELD) == MANAGED_BY


def bound_entity_of(child: Mapping[str, Any]) -> str | None:
    """Return the first HA entity id referenced by a raw mapping child."""

    bindings = child.get("bindings")
    if not isinstance(bindings, list):
        return None
    for binding in bindings:
        if not isinstance(binding, dict):
            continue
        fields = binding.get("fields")
        if not isinstance(fields, dict):
            continue
        for field in fields.values():
            if (
                isinstance(field, dict)
                and isinstance(field.get("entity_id"), str)
                and field["entity_id"]
            ):
                return field["entity_id"]
    return None


def managed_children(raw: Any) -> dict[str, dict[str, Any]]:
    """Return the entity-bridge-managed children of a raw mapping document."""

    if not isinstance(raw, dict):
        return {}
    children = raw.get("children")
    if not isinstance(children, dict):
        return {}
    return {
        key: child for key, child in children.items() if is_managed_child(child)
    }


def build_child_mapping(
    entity_id: str,
    *,
    name: str | None = None,
    attributes: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Build one raw mapping child entry for a selected HA entity."""

    domain = entity_id.split(".", 1)[0]
    if domain not in BRIDGEABLE_DOMAINS:
        raise ValueError(f"unsupported domain for entity bridge: {domain}")
    display_name = name or entity_id
    if domain == "light":
        child = _build_light_child(entity_id, display_name, dict(attributes or {}))
    elif domain == "lock":
        child = _build_lock_child(entity_id, display_name)
    elif domain in {"switch", "input_boolean"}:
        child = _build_state_switch_child(entity_id, display_name)
    else:  # script / scene / button: momentary wrapper with constant-off display
        child = _build_momentary_child(entity_id, display_name)
    child[MANAGED_BY_FIELD] = MANAGED_BY
    return child


def apply_entity_selection(
    raw: Any,
    *,
    gateway_serial: str,
    selected_children: Mapping[str, Mapping[str, Any]],
) -> dict[str, Any]:
    """Merge selected entity children into a raw mapping document.

    - 手写 children 原样保留；
    - 受管 children 中未被再次勾选的条目被删除；
    - selected_children 覆盖同 key 的受管条目（保留手写调整需在勾选时透传原条目）。
    """

    if not isinstance(raw, dict):
        raw = {}
    result = {key: value for key, value in raw.items() if key != "children"}
    old_children = raw.get("children")
    old_children = dict(old_children) if isinstance(old_children, dict) else {}

    children: dict[str, Any] = {}
    for key, child in old_children.items():
        if is_managed_child(child) and key not in selected_children:
            continue
        children[key] = child
    for key, child in selected_children.items():
        existing = children.get(key)
        if existing is not None and not is_managed_child(existing):
            raise ValueError(
                f"child key {key} conflicts with a handwritten mapping entry"
            )
        children[key] = child

    if len(children) > MAX_CHILD_DEVICES_PER_GATEWAY:
        raise ValueError(
            f"selection exceeds the {MAX_CHILD_DEVICES_PER_GATEWAY} child device limit"
        )

    result["schema"] = 1
    result["enabled"] = True
    result["gateway_serial"] = gateway_serial
    result["children"] = children
    return result


def _build_state_switch_child(entity_id: str, name: str) -> dict[str, Any]:
    return {
        "display": {"friendly_name": name},
        "product": {
            "ref": "ZG2R",
            "services": [dict(service) for service in _SWITCH_SERVICES],
        },
        "bindings": [
            {
                "sid": "switch1",
                "fields": {
                    "on": {
                        "entity_id": entity_id,
                        "source": "state",
                        "ha_to_huawei": {
                            "type": "state_map",
                            "map": {"on": 1, "off": 0},
                        },
                        "huawei_to_ha": {
                            "type": "state_map",
                            "map": {"0": "off", "1": "on"},
                        },
                    }
                },
            }
        ],
    }


def _build_momentary_child(entity_id: str, name: str) -> dict[str, Any]:
    """Script/scene/button wrapper: always shown off, command triggers once."""

    return {
        "display": {"friendly_name": name},
        "product": {
            "ref": "ZG2R",
            "services": [dict(service) for service in _SWITCH_SERVICES],
        },
        "bindings": [
            {
                "sid": "switch1",
                "fields": {
                    "on": {
                        "entity_id": entity_id,
                        "source": "constant",
                        "value": 0,
                    }
                },
            }
        ],
    }


def _build_lock_child(entity_id: str, name: str) -> dict[str, Any]:
    return {
        "display": {"friendly_name": name},
        "product": {
            "ref": "ZG2R",
            "services": [dict(service) for service in _SWITCH_SERVICES],
        },
        "bindings": [
            {
                "sid": "switch1",
                "fields": {
                    "on": {
                        "entity_id": entity_id,
                        "source": "state",
                        "ha_to_huawei": {
                            "type": "state_map",
                            "map": {
                                "locked": 1,
                                "locking": 1,
                                "unlocked": 0,
                                "unlocking": 0,
                                "jammed": 0,
                                "open": 0,
                            },
                        },
                    }
                },
            }
        ],
    }


_LIGHT_FULL_COLOR_MODES = {"rgb", "rgbw", "rgbww", "hs", "xy"}


def _light_product_id(attributes: Mapping[str, Any]) -> str:
    modes = attributes.get("supported_color_modes")
    mode_set = set(modes) if isinstance(modes, (list, tuple, set)) else set()
    if mode_set & _LIGHT_FULL_COLOR_MODES:
        return "ZG0O"
    if "color_temp" in mode_set:
        return "ZG13"
    if mode_set & {"brightness", "white"} or "brightness" in attributes:
        return "ZG14"
    return "ZG0S"


def _build_light_child(
    entity_id: str, name: str, attributes: Mapping[str, Any]
) -> dict[str, Any]:
    product_id = _light_product_id(attributes)
    child: dict[str, Any] = {
        "display": {"friendly_name": name},
        "product": {
            "ref": product_id,
            "services": [
                {"st": "switch", "sid": "switch"},
            ],
        },
        "bindings": [
            {
                "sid": "switch",
                "fields": {
                    "on": {
                        "entity_id": entity_id,
                        "source": "state",
                        "ha_to_huawei": {
                            "type": "state_map",
                            "map": {"on": 1, "off": 0},
                        },
                        "huawei_to_ha": {
                            "type": "state_map",
                            "map": {"0": "off", "1": "on"},
                        },
                    }
                },
            }
        ],
    }
    if product_id in {"ZG14", "ZG13", "ZG0O"}:
        child["product"]["services"].append({"st": "brightness", "sid": "brightness"})
        child["bindings"].append(
            {
                "sid": "brightness",
                "fields": {
                    "brightness": {
                        "entity_id": entity_id,
                        "source": "attribute",
                        "attribute": "brightness",
                    }
                },
            }
        )
    if product_id in {"ZG13", "ZG0O"}:
        child["product"]["services"].append({"st": "cct", "sid": "cct"})
        child["bindings"].append(
            {
                "sid": "cct",
                "fields": {
                    "colorTemperature": {
                        "entity_id": entity_id,
                        "source": "attribute",
                        "attribute": "color_temp_kelvin",
                    }
                },
            }
        )
    if product_id == "ZG0O":
        child["product"]["services"].insert(
            0, {"st": "subProduct", "sid": "subProduct"}
        )
        child["product"]["services"].append({"st": "colour", "sid": "colour"})
        child["bindings"].insert(
            0,
            {
                "sid": "subProduct",
                "fields": {"subProductId": {"source": "constant", "value": "05"}},
            },
        )
        child["bindings"].append(
            {
                "sid": "colour",
                "fields": {
                    component: {
                        "entity_id": entity_id,
                        "source": "attribute",
                        "attribute": "rgb_color",
                        "component": component,
                    }
                    for component in ("red", "green", "blue")
                },
            }
        )
    return child
