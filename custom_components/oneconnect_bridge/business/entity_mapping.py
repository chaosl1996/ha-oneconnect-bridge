def _on_state_binding(entity_id: str, sid: str) -> dict[str, Any]:
    return {
        "sid": sid,
        "fields": {
            "on": {
                "entity_id": entity_id,
                "source": "state",
                "ha_to_huawei": {
                    "type": "state_map",
                    "map": {"on": 1, "off": 0},
                },
                "huawei_to_ha": {
                    "type": "state_map",
                    "map": {"0": "off", "1": "on"},
                },
            }
        },
    }


def _attribute_binding(
    entity_id: str, sid: str, field_name: str, attribute: str
) -> dict[str, Any]:
    return {
        "sid": sid,
        "fields": {
            field_name: {
                "entity_id": entity_id,
                "source": "attribute",
                "attribute": attribute,
            }
        },
    }


def _colour_binding(entity_id: str) -> dict[str, Any]:
    return {
        "sid": "colour",
        "fields": {
            component: {
                "entity_id": entity_id,
                "source": "attribute",
                "attribute": "rgb_color",
                "component": component,
            }
            for component in ("red", "green", "blue")
        },
    }


