"""Entity-level child mapping builder (HomeKit-Bridge style selection).

将用户在配置界面勾选的 HA 实体转换为 mapping.yaml 的 children 条目：

- switch / input_boolean → 开关产品（真实状态绑定，默认 ZG2R）
- light → 按能力自动选型，或用户指定产品：单色 / 调光 / 调色温 / 全彩
- lock → 开关包装（锁定=开，解锁=关）
- script / scene / button / input_button → 开关包装（常量 0 显示 + 命令触发）

用户可在配置界面为每个实体指定华为产品型号（catalog.yaml 中存在的
产品 ref）；未指定时按实体域与能力自动选择。生成的条目带
``managed_by: entity_bridge`` 标记：合并时只增删这些条目，用户手写的
children 永远不会被覆盖或删除。

本模块不依赖 Home Assistant，可独立单测。
"""

from __future__ import annotations

from typing import Any, Mapping

from ..const import BRIDGEABLE_DOMAINS, MAX_CHILD_DEVICES_PER_GATEWAY

MANAGED_BY_FIELD = "managed_by"
MANAGED_BY = "entity_bridge"

_MOMENTARY_DOMAINS = frozenset({"script", "scene", "button", "input_button"})
_STATE_DOMAINS = frozenset({"switch", "input_boolean"})

# 产品 ref → 服务模板档位。档位决定 services 与 bindings 的结构。
# switchN = N 键开关（声明全部键位服务，仅绑定第一键）；其余为灯类档位。
_PRODUCT_TEMPLATES = {
    "ZG2R": "switch1",
    "ZG2S": "switch2",
    "ZG2T": "switch3",
    "ZG0S": "single",
    "ZG0R": "single",
    "ZG0T": "single",
    "ZG0U": "single",
    "ZG0V": "single",
    "ZG0W": "single",
    "ZG0X": "single",
    "ZG0Y": "single",
    "ZG14": "dim",
    "ZG13": "cct",
    "ZG17": "cct",
    "ZG2F": "cct",
    "ZG2G": "cct",
    "ZG2H": "cct",
    "ZG2I": "cct",
    "ZG2J": "cct",
    "ZG0O": "fullcolor",
}

# 配置界面下拉可选项：按实体域过滤的 device_type 集合。
_LIGHT_DEVICE_TYPES = frozenset(
    {"A0E", "A1A", "A1B", "A1C", "A1D", "A1E", "A1F", "A20", "A21"}
)
_SWITCH_DEVICE_TYPES = frozenset({"A13"})


def child_key_for_entity(entity_id: str) -> str:
    """Return a stable, storage-safe child key for one HA entity id."""

    return "".join(
        char if (char.isascii() and char.isalnum()) or char in "_-" else "_"
        for char in entity_id
    )


def is_managed_child(child: Any) -> bool:
    """Return whether a raw mapping child was generated by the entity bridge."""

    return isinstance(child, dict) and child.get(MANAGED_BY_FIELD) == MANAGED_BY


def bound_entity_of(child: Mapping[str, Any]) -> str | None:
    """Return the first HA entity id referenced by a raw mapping child."""

    bindings = child.get("bindings")
    if not isinstance(bindings, list):
        return None
    for binding in bindings:
        if not isinstance(binding, dict):
            continue
        fields = binding.get("fields")
        if not isinstance(fields, dict):
            continue
        for field in fields.values():
            if (
                isinstance(field, dict)
                and isinstance(field.get("entity_id"), str)
                and field["entity_id"]
            ):
                return field["entity_id"]
    return None


def managed_children(raw: Any) -> dict[str, dict[str, Any]]:
    """Return the entity-bridge-managed children of a raw mapping document."""

    if not isinstance(raw, dict):
        return {}
    children = raw.get("children")
    if not isinstance(children, dict):
        return {}
    return {
        key: child for key, child in children.items() if is_managed_child(child)
    }


def product_options(
    catalog: Mapping[str, Any], domain: str
) -> dict[str, str]:
    """Build {prod_id: label} choices for one entity domain's dropdown.

    catalog 为 load_catalog() 的结果；灯实体可选全部灯类产品，
    其余实体可选开关类产品。
    """

    wanted = _LIGHT_DEVICE_TYPES if domain == "light" else _SWITCH_DEVICE_TYPES
    options: dict[str, str] = {}
    for prod_id in sorted(catalog):
        spec = catalog[prod_id]
        if spec.device_type not in wanted:
            continue
        options[prod_id] = f"{spec.device_name} ({prod_id})"
    return options


def build_child_mapping(
    entity_id: str,
    *,
    name: str | None = None,
    attributes: Mapping[str, Any] | None = None,
    product_ref: str | None = None,
) -> dict[str, Any]:
    """Build one raw mapping child entry for a selected HA entity.

    product_ref 指定时使用该产品的服务模板；未指定时灯按能力自动选型，
    其余实体使用默认开关产品。
    """

    domain = entity_id.split(".", 1)[0]
    if domain not in BRIDGEABLE_DOMAINS:
        raise ValueError(f"unsupported domain for entity bridge: {domain}")
    display_name = name or entity_id
    if product_ref is not None:
        child = _build_product_child(entity_id, display_name, product_ref)
    elif domain == "light":
        child = _build_product_child(
            entity_id, display_name, _light_product_id(dict(attributes or {}))
        )
    elif domain == "lock":
        child = _build_lock_child(entity_id, display_name)
    elif domain in _STATE_DOMAINS:
        child = _build_state_switch_child(entity_id, display_name)
    else:  # script / scene / button / input_button: 常关显示 + 命令触发
        child = _build_momentary_child(entity_id, display_name)
    child[MANAGED_BY_FIELD] = MANAGED_BY
    return child


def apply_entity_selection(
    raw: Any,
    *,
    gateway_serial: str,
    selected_children: Mapping[str, Mapping[str, Any]],
) -> dict[str, Any]:
    """Merge selected entity children into a raw mapping document.

    - 手写 children 原样保留；
    - 受管 children 中未被再次勾选的条目被删除；
    - selected_children 覆盖同 key 的受管条目（保留手写调整需在勾选时透传原条目）。
    """

    if not isinstance(raw, dict):
        raw = {}
    result = {key: value for key, value in raw.items() if key != "children"}
    old_children = raw.get("children")
    old_children = dict(old_children) if isinstance(old_children, dict) else {}

    children: dict[str, Any] = {}
    for key, child in old_children.items():
        if is_managed_child(child) and key not in selected_children:
            continue
        children[key] = child
    for key, child in selected_children.items():
        existing = children.get(key)
        if existing is not None and not is_managed_child(existing):
            raise ValueError(
                f"child key {key} conflicts with a handwritten mapping entry"
            )
        children[key] = child

    if len(children) > MAX_CHILD_DEVICES_PER_GATEWAY:
        raise ValueError(
            f"selection exceeds the {MAX_CHILD_DEVICES_PER_GATEWAY} child device limit"
        )

    result["schema"] = 1
    result["enabled"] = True
    result["gateway_serial"] = gateway_serial
    result["children"] = children
    return result


